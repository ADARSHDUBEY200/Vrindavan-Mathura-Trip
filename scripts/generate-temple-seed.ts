/**
 * Writes supabase-temples.sql: the migration for the Temple editor, plus the site's existing temple guides
 * and the /temples page copy as seed rows. This only writes a local file; nothing here touches the database.
 *
 * Run from the project root:  npx tsx scripts/generate-temple-seed.ts
 */
import { writeFileSync } from "node:fs";
import { templesPage } from "../src/content/temples-page";
import { defaultTempleRows } from "../src/lib/cms/temple-defaults";

const text = (v: string) => `'${v.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${text(JSON.stringify(v))}::jsonb`;

const rows = defaultTempleRows();
const columns = ["title", "location", "slug", "meta", "schema", "image", "alt", "subcontent", "content", "history", "timing", "bestvisit", "journey", "templeoverview", "quickanswer", "ataglance", "whybook", "faqs", "details", "status"] as const;

const values = rows.map((r) => `  (${columns.map((c) => (typeof r[c] === "string" ? text(r[c]) : json(r[c]))).join(", ")})`).join(",\n");

const sql = `-- =====================================================================
-- vrindavanmathuratrip: Temple CMS
-- Paste this whole file into the Supabase SQL editor and press Run. Run it once.
-- Generated by scripts/generate-temple-seed.ts. Edit that script, not this file.
--
-- 1. Adds "details" to Temple: darshan and aarti timings, address, map, routes,
--    gallery, nearby, related, festivals, custom sections and page layout.
--    Row shape: TempleDetails in src/lib/cms/temple-fields.ts.
-- 2. Adds the site's ${rows.length} existing temple guides as published rows, so every
--    /temples link keeps working and each guide can be edited in the CMS.
-- 3. Adds the /temples page copy from the PDF as the published "temples" page.
--
-- Safe to re-run: "on conflict do nothing" never overwrites a row you have edited.
-- Nothing is deleted, and Blog, Package and the other SitePage rows are not touched.
-- =====================================================================

alter table public."Temple" add column if not exists details jsonb not null default '{}'::jsonb;

insert into public."Temple" (${columns.join(", ")})
values
${values}
on conflict (slug) do nothing;

insert into public."SitePage" (slug, title, content, status)
values ('temples', 'Temples Page', ${json(templesPage)}, 'published')
on conflict (slug) do nothing;

-- Tell the API about the new column straight away.
notify pgrst, 'reload schema';

-- ---------------------------------------------------------------------
-- Check: expect details_column = 1, temples = ${rows.length}, temples_page = 1
-- ---------------------------------------------------------------------
select
  (select count(*) from information_schema.columns where table_schema = 'public' and table_name = 'Temple' and column_name = 'details') as details_column,
  (select count(*) from public."Temple" where status = 'published') as temples,
  (select count(*) from public."SitePage" where slug = 'temples') as temples_page;
`;

writeFileSync("supabase-temples.sql", sql);
console.log(`supabase-temples.sql: ${rows.length} temples, ${(sql.length / 1024).toFixed(0)} KB`);
